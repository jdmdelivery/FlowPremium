def get_locale():
    from flask import session
    from flask import current_app
    return session.get("locale", current_app.config.get("DEFAULT_LOCALE", "es"))


def t(key: str) -> str:
    locale = get_locale()
    return TRANSLATIONS.get(locale, TRANSLATIONS["es"]).get(key, key)


def get_all_translations():
    locale = get_locale()
    return TRANSLATIONS.get(locale, TRANSLATIONS["es"])
